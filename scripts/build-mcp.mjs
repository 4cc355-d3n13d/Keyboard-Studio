import {readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const read=p=>readFile(resolve(root,p),'utf8');
const source=await read('web/index.html');
const presetText=source.slice(source.indexOf('const presets=['),source.indexOf('const presetGroups='));
const catalog=[...presetText.matchAll(/\{name:'([^']+)',description:'([^']+)'/g)].map((m,id)=>({id,name:m[1],description:m[2]}));
const groupText=source.slice(source.indexOf('const presetGroups='),source.indexOf('const midiPrograms='));
for(const match of groupText.matchAll(/\['([^']+)',\[([^\]]+)\]\]/g))for(const id of JSON.parse('['+match[2]+']'))catalog[id].category=match[1];
if(catalog.length!==36||catalog.some(p=>!p.category))throw Error('Invalid instrument catalog');
const catalogJS='const MCP_CATALOG='+JSON.stringify(catalog)+';\n';
const protocol=await read('mcp/protocol.js'),bridge=await read('mcp/browser.js'),backend=await read('worker/server.js');
const marker='/* ORBIT_MCP_BRIDGE */';if(!source.includes(marker))throw Error('Bridge marker missing');
const html=source.replace(marker,catalogJS+protocol+'\n'+bridge);
const tone=await read('web/tone.js'),license=await read('web/Tone.js.LICENSE.txt');
const prefix='const ORBIT_HTML='+JSON.stringify(html)+';\nconst ORBIT_TONE='+JSON.stringify(tone)+';\nconst ORBIT_LICENSE='+JSON.stringify(license)+';\n';
await rm(resolve(root,'dist'),{recursive:true,force:true});await mkdir(resolve(root,'dist/server'),{recursive:true});await mkdir(resolve(root,'dist/.openai'),{recursive:true});
await writeFile(resolve(root,'dist/server/index.js'),prefix+catalogJS+protocol+'\n'+backend);
await writeFile(resolve(root,'dist/.openai/hosting.json'),await read('.openai/hosting.json'));
await mkdir(resolve(root,'build'),{recursive:true});await writeFile(resolve(root,'build/index.html'),html);await writeFile(resolve(root,'build/catalog.json'),JSON.stringify(catalog,null,2));
const standalone=html.replace('<script src="tone.js"></script>','<script>\n'+license+'\n'+tone.replaceAll('</script','<\\/script')+'\n</script>');await writeFile(resolve(root,'build/music-keyboard-studio.html'),standalone);
console.log('Built ORBIT Worker with '+catalog.length+' instruments and MCP browser bridge.');
